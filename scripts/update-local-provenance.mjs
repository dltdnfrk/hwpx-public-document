#!/usr/bin/env node
import { createHash } from 'node:crypto'
import { readFileSync, renameSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import vm from 'node:vm'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const check = process.argv.includes('--check')
const toolkitPath = 'Resources/Templates/official-style-toolkit-1.0.0.json'
const tokensPath = 'Resources/Print/print-tokens-1.0.0.json'
const profilePath = 'Resources/Studio/official-layout-profile.js'
const manifestPath = 'provenance/genoffice-docs-port.json'
const lockPath = 'provenance/upstream-lock.json'

const absolute = (relative) => path.resolve(root, relative)
const bytes = (relative) => readFileSync(absolute(relative))
const readJSON = (relative) => JSON.parse(readFileSync(absolute(relative), 'utf8'))
const sha256Bytes = (value) => createHash('sha256').update(value).digest('hex')
const sha256 = (relative) => `sha256:${sha256Bytes(bytes(relative))}`
const writeAtomic = (relative, value) => {
  const destination = absolute(relative)
  const temporary = `${destination}.tmp.${process.pid}`
  writeFileSync(temporary, value)
  renameSync(temporary, destination)
}
const writeJSON = (relative, value) => {
  writeAtomic(relative, `${JSON.stringify(value, null, 2)}\n`)
}
const safeRelativePath = (relative) => (
  typeof relative === 'string'
  && relative.length > 0
  && !path.isAbsolute(relative)
  && !relative.includes('\\')
  && !/^[A-Za-z]:[\\/]/.test(relative)
  && !relative.startsWith('//')
  && path.normalize(relative) === relative
  && !relative.split(path.sep).includes('..')
  && absolute(relative).startsWith(`${root}${path.sep}`)
)

const toolkitData = bytes(toolkitPath)
const tokensData = bytes(tokensPath)
const toolkit = JSON.parse(toolkitData)
const tokens = JSON.parse(tokensData)
const fingerprintInput = Buffer.concat([
  Buffer.from(toolkit.toolkitID),
  Buffer.from([0]),
  toolkitData,
  Buffer.from([0]),
  Buffer.from(tokens.tokenID),
  Buffer.from([0]),
  tokensData,
])
const expectedProfile = {
  schemaVersion: 1,
  profileID: 'official-layout-profile-1.0.0',
  profileFingerprint: `sha256:${sha256Bytes(fingerprintInput)}`,
  sources: {
    toolkit: { id: toolkit.toolkitID, sha256: sha256(toolkitPath) },
    printTokens: { id: tokens.tokenID, sha256: sha256(tokensPath) },
  },
  page: tokens.page,
  fonts: tokens.fonts,
  sizesPt: tokens.sizesPt,
  presets: toolkit.presets,
  presetOrder: toolkit.presetOrder,
  guidebookList: toolkit.guidebookList,
  statutoryList: toolkit.statutoryList,
  letterSpacing: toolkit.operations['word-keep'].letterSpacing,
}

const canonical = (value) => {
  if (Array.isArray(value)) return value.map(canonical)
  if (value && typeof value === 'object') {
    return Object.fromEntries(
      Object.keys(value).sort().map((key) => [key, canonical(value[key])]),
    )
  }
  return value
}
const equal = (left, right) => (
  JSON.stringify(canonical(left)) === JSON.stringify(canonical(right))
)
const currentProfile = (() => {
  const source = readFileSync(absolute(profilePath), 'utf8')
  const declaration = 'const PublicDocumentOfficialLayoutProfile = '
  const declarationIndex = source.indexOf(declaration)
  if (
    declarationIndex < 0
    || !source.slice(0, declarationIndex).split('\n').every(
      (line) => line.length === 0 || line.startsWith('// '),
    )
    || !source.includes('globalThis.PublicDocumentOfficialLayoutProfile = PublicDocumentOfficialLayoutProfile')
    || /\b(?:eval|Function|require|process|constructor|while|for)\b|=>/.test(
      source.slice(declarationIndex),
    )
  ) {
    throw new Error('generated profile source contains unsupported executable syntax')
  }
  const sandbox = {}
  sandbox.globalThis = sandbox
  vm.runInNewContext(source, sandbox, {
    timeout: 100,
    codeGeneration: { strings: false, wasm: false },
  })
  return JSON.parse(JSON.stringify(sandbox.PublicDocumentOfficialLayoutProfile))
})()

const renderProfile = (profile) => (
  `// Generated by scripts/update-local-provenance.mjs. Do not edit by hand.\n`
  + `const PublicDocumentOfficialLayoutProfile = ${JSON.stringify(profile, null, 2)}\n\n`
  + 'globalThis.PublicDocumentOfficialLayoutProfile = PublicDocumentOfficialLayoutProfile\n'
  + 'if (typeof module === \"object\" && module.exports) module.exports = PublicDocumentOfficialLayoutProfile\n'
)

const stale = []
if (!equal(currentProfile, expectedProfile)) stale.push(profilePath)
if (!check && stale.includes(profilePath)) {
  writeAtomic(profilePath, renderProfile(expectedProfile))
}

const manifest = readJSON(manifestPath)
const declared = new Set(manifest.portBoundary.shippedLocalArtifacts)
const artifacts = new Set(manifest.localArtifacts.map((item) => item.path))
if (
  declared.size !== manifest.portBoundary.shippedLocalArtifacts.length
  || artifacts.size !== manifest.localArtifacts.length
) {
  throw new Error('local artifact inventories contain duplicate paths')
}
for (const artifactPath of [...declared, ...artifacts]) {
  if (!safeRelativePath(artifactPath)) {
    throw new Error(`unsafe local artifact path: ${artifactPath}`)
  }
}
if (!equal([...declared].sort(), [...artifacts].sort())) {
  throw new Error('local artifact boundary and manifest inventory differ')
}
for (const artifact of manifest.localArtifacts) {
  const digest = sha256(artifact.path)
  if (artifact.sha256 !== digest) {
    stale.push(`${manifestPath}:${artifact.path}`)
    artifact.sha256 = digest
  }
}
if (!check && stale.some((item) => item.startsWith(`${manifestPath}:`))) {
  writeJSON(manifestPath, manifest)
}

const lock = readJSON(lockPath)
const genoffice = lock.upstreams.find((item) => item.name === 'genoffice')
if (!genoffice) throw new Error('genoffice upstream lock entry is missing')
const manifestDigest = sha256(manifestPath)
if (genoffice.port_manifest_sha256 !== manifestDigest) {
  stale.push(`${lockPath}:port_manifest_sha256`)
  genoffice.port_manifest_sha256 = manifestDigest
}
if (!check && stale.some((item) => item.startsWith(`${lockPath}:`))) {
  writeJSON(lockPath, lock)
}

const receipt = {
  status: stale.length === 0 ? 'current' : check ? 'stale' : 'updated',
  profile: profilePath,
  manifest: manifestPath,
  lock: lockPath,
  profileFingerprint: expectedProfile.profileFingerprint,
  stale,
}
process.stdout.write(`${JSON.stringify(receipt, null, 2)}\n`)
if (check && stale.length > 0) process.exitCode = 1
